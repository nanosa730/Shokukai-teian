from wordtool import Doc,T
d=Doc('a120.docx')
def setp(i,text):
    """段落iの1つ目のランに文字を入れ、残りのランは空にする"""
    m=d.paras()[i]; k=[-1]
    def f(a):
        k[0]+=1; return a.group(1)+(text if k[0]==0 else '')+a.group(3)
    d.x=d.x[:m.start()]+re.sub(T,f,m.group(0))+d.x[m.end():]
def addafter(i,text):
    """段落iを複製して直後に置き、文字を差し替える"""
    m=d.paras()[i]; p=m.group(0); k=[-1]
    def f(a):
        k[0]+=1; return a.group(1)+(text if k[0]==0 else '')+a.group(3)
    d.x=d.x[:m.end()]+re.sub(T,f,p)+d.x[m.end():]
