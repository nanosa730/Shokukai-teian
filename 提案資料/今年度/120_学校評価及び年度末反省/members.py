B={}
def add(bu,names,mark='○',label=''):
    for n in names.split():
        cur=B.setdefault(bu,{}).get(n,'')
        new=mark+label
        if cur.startswith('●') or cur.startswith('◎'):
            if mark=='○': continue
        B[bu][n]=(cur.replace('○','')+new) if mark!='○' and cur else (new if not cur else cur)
